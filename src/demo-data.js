// 아티팩트처럼 같은 날 같은 과목(수업 + 클리닉)은 한 일정으로 묶어서 캘린더 일정 모양으로 바꿈
const mm=t=>{const[h,m]=t.split(":").map(Number);return h*60+m};
export function demoEvents(){
  const g=new Map();
  E.forEach(e=>{const k=e.date+"|"+e.s;if(!g.has(k))g.set(k,[]);g.get(k).push(e);});
  const out=[];
  g.forEach((a,k)=>{const t=a.filter(e=>e.start);if(!t.length)return;
    const [date,s]=k.split("|"),[y,mo,d]=date.split("-").map(Number);
    const st=Math.min(...t.map(e=>mm(e.start))),en=Math.max(...t.map(e=>e.end?mm(e.end):mm(e.start)+120));
    const boost=a.some(e=>e.kind.includes("보강")),note=a.find(e=>e.note);
    out.push({id:k,title:S[s].name+(boost?"·보강":""),start:new Date(y,mo-1,d,0,st),end:new Date(y,mo-1,d,0,en),allDay:false,
      color:S[s].c,calendar:S[s].full,location:"",
      notes:a.map(p=>`${p.kind} ${p.start?p.start+(p.end?"–"+p.end:"~"):"시간 미정"}`).join(" · ")+(note?"\n"+note.note:"")});});
  return out;}
